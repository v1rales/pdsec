"""Вспомогательный модуль контекста ПД.

Определяет, относится ли фрагмент текста к персональным данным, по наличию
рядом контекстных маркеров (клиент, паспорт, родился, проживает, гражданин).
Используется другими детекторами для повышения уверенности.
"""

import re

#: Контекстные маркеры, указывающие на принадлежность к ПД.
_PD_MARKERS = (
    "клиент", "клиента", "клиенту", "клиентом",
    "паспорт", "паспорта", "паспорту", "паспортом",
    "родился", "родилась", "родился(ась)",
    "проживает", "проживающ", "прожива",
    "гражданин", "гражданка", "гражданина", "гражданки",
    "зарегистрирован", "зарегистрирована",
    "место рождения", "место жительства",
)

#: Скомпилированный паттерн поиска маркеров (регистронезависимо).
_MARKER_RE = re.compile(
    r"(?:"
    + "|".join(re.escape(m) for m in _PD_MARKERS)
    + r")",
    re.IGNORECASE,
)


def has_pd_context(text: str, start: int, end: int, window: int = 60) -> bool:
    """Возвращает True, если рядом с фрагментом [start, end) есть контекст ПД.

    Окно поиска — `window` символов слева и справа от фрагмента.
    """
    left = max(0, start - window)
    right = min(len(text), end + window)
    context = text[left:right]
    return _MARKER_RE.search(context) is not None